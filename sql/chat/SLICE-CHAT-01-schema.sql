-- Schema extensibila; momentan exista numai conversatia COMUN.
SET time_zone = '+00:00';
CREATE TABLE IF NOT EXISTS AVACONT_COMUN.CHAT_IDENTITATI (
    ID_UTILIZATOR BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    CONT VARCHAR(255) NOT NULL,
    PSEUDONIM VARCHAR(48) NOT NULL,
    NUME_AFISAT VARCHAR(80) NOT NULL DEFAULT '',
    CREAT_LA DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (ID_UTILIZATOR),
    UNIQUE KEY UQ_CHAT_CONT (CONT),
    UNIQUE KEY UQ_CHAT_PSEUDONIM (PSEUDONIM)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS AVACONT_COMUN.CHAT_CONVERSATII (
    ID_CONVERSATIE BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    CHEIE VARCHAR(80) NOT NULL,
    TIP VARCHAR(24) NOT NULL DEFAULT 'COMUN',
    TITLU VARCHAR(120) NOT NULL,
    CREAT_LA DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (ID_CONVERSATIE),
    UNIQUE KEY UQ_CHAT_CONVERSATIE (CHEIE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS AVACONT_COMUN.CHAT_PARTICIPANTI (
    ID_CONVERSATIE BIGINT UNSIGNED NOT NULL,
    ID_UTILIZATOR BIGINT UNSIGNED NOT NULL,
    FILTRU_APLICATII VARCHAR(3) NOT NULL DEFAULT 'VAK',
    ANONIM_IMPLICIT TINYINT(1) NOT NULL DEFAULT 1,
    INTRAT_LA DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (ID_CONVERSATIE, ID_UTILIZATOR),
    CONSTRAINT FK_CHAT_PART_CONV FOREIGN KEY (ID_CONVERSATIE)
        REFERENCES AVACONT_COMUN.CHAT_CONVERSATII (ID_CONVERSATIE),
    CONSTRAINT FK_CHAT_PART_USER FOREIGN KEY (ID_UTILIZATOR)
        REFERENCES AVACONT_COMUN.CHAT_IDENTITATI (ID_UTILIZATOR)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS AVACONT_COMUN.CHAT_MESAJE (
    ID_MESAJ BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    ID_CONVERSATIE BIGINT UNSIGNED NOT NULL,
    ID_UTILIZATOR BIGINT UNSIGNED NOT NULL,
    APLICATIE CHAR(1) NOT NULL,
    ANONIM TINYINT(1) NOT NULL,
    NUME_AUTOR VARCHAR(80) NOT NULL DEFAULT '',
    CONTINUT TEXT NOT NULL,
    RASPUNS_LA BIGINT UNSIGNED NULL,
    CHEIE_CLIENT CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    CREAT_LA DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (ID_MESAJ),
    UNIQUE KEY UQ_CHAT_RETRIMITERE (ID_UTILIZATOR, CHEIE_CLIENT),
    KEY IX_CHAT_FLUX (ID_CONVERSATIE, ID_MESAJ),
    KEY IX_CHAT_APLICATIE (ID_CONVERSATIE, APLICATIE, ID_MESAJ),
    KEY IX_CHAT_AUTOR (ID_UTILIZATOR, CREAT_LA),
    CONSTRAINT FK_CHAT_MSG_PART FOREIGN KEY (ID_CONVERSATIE, ID_UTILIZATOR)
        REFERENCES AVACONT_COMUN.CHAT_PARTICIPANTI (ID_CONVERSATIE, ID_UTILIZATOR),
    CONSTRAINT FK_CHAT_MSG_REPLY FOREIGN KEY (RASPUNS_LA)
        REFERENCES AVACONT_COMUN.CHAT_MESAJE (ID_MESAJ),
    CONSTRAINT CK_CHAT_MSG_APP CHECK (APLICATIE IN ('V', 'A', 'K')),
    CONSTRAINT CK_CHAT_MSG_ANONIM CHECK (ANONIM IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS AVACONT_COMUN.CHAT_CITIRI (
    ID_CONVERSATIE BIGINT UNSIGNED NOT NULL,
    ID_UTILIZATOR BIGINT UNSIGNED NOT NULL,
    APLICATIE CHAR(1) NOT NULL,
    ULTIMUL_MESAJ BIGINT UNSIGNED NOT NULL DEFAULT 0,
    CITIT_LA DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (ID_CONVERSATIE, ID_UTILIZATOR, APLICATIE),
    CONSTRAINT FK_CHAT_CIT_PART FOREIGN KEY (ID_CONVERSATIE, ID_UTILIZATOR)
        REFERENCES AVACONT_COMUN.CHAT_PARTICIPANTI (ID_CONVERSATIE, ID_UTILIZATOR),
    CONSTRAINT CK_CHAT_CIT_APP CHECK (APLICATIE IN ('V', 'A', 'K'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

